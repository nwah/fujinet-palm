def write_bmp(path, rows, w, h):
    rows = [r for r in rows.strip('\n').split('\n')]
    rows += ['.' * w] * (h - len(rows))
    stride = ((w + 31) // 32) * 4
    pix = b''
    for r in reversed(rows[:h]):          # BMP is bottom-up
        bits = bytearray(stride)
        for x, c in enumerate(r[:w]):
            if c != '#':                  # palette 1 = white
                bits[x // 8] |= 0x80 >> (x % 8)
        pix += bytes(bits)
    pal = b'\x00\x00\x00\x00\xff\xff\xff\x00'
    off = 14 + 40 + len(pal)
    hdr = b'BM' + struct.pack('<IHHI', off + len(pix), 0, 0, off)
    dib = struct.pack('<IiiHHIIiiII', 40, w, h, 1, 1, 0, len(pix), 2835, 2835, 2, 2)
    open(path, 'wb').write(hdr + dib + pal + pix)

for n in L:
    if n in ('host', 'top'):
        continue
    write_bmp(f'{n}_l.bmp', L[n], 32, 32)
    write_bmp(f'{n}_s.bmp', S[n], 15, 9)
